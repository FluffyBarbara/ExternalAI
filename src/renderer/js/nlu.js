function num(t) {
  const m = t.match(/(\d+)/);
  return m ? ` на ${m[1]}` : '';
}
function place(t) {
  const m = t.match(/\s(в|во)\s+([а-я-]+(?:\s+[а-я-]+)?)/);
  const day = /послезавтра/.test(t) ? ' послезавтра' : /завтра/.test(t) ? ' завтра' : '';
  return (m ? ` в ${m[2].replace(/\s+(завтра|послезавтра|сегодня)$/, '')}` : '') + day;
}
function currencyWord(t) {
  if (/евро/.test(t)) return 'евро';
  if (/юан/.test(t)) return 'юаня';
  return 'доллара';
}

/** Угадывает каноническую команду по ключевым словам, если правила не сработали. */
export function guessIntent(t) {
  const words = t.split(' ');
  for (const g of GUESS) {
    if (g.all.every((stems) => has(words, stems))) {
      const out = g.to(t);
      if (out && out !== t) return out;
    }
  }
  return null;
}

/** Похожесть двух фраз: целиком и по словам (порядок слов не важен). */
export function phraseSimilarity(a, b) {
  if (a === b) return 1;
  const whole = similarity(a, b);
  const wa = a.split(' ');
  const wb = b.split(' ');
  if (Math.abs(wa.length - wb.length) > 1) return whole;
  let sum = 0;
  for (const x of wa) sum += Math.max(...wb.map((y) => similarity(x, y)));
  const words = sum / Math.max(wa.length, wb.length);
  return Math.max(whole, words);
}

/** Разбивает действие на несколько команд: «открой телеграм и включи музыку». */
export function splitActions(text) {
  const parts = String(text)
    .split(/\s*(?:,|;|\sи потом\s|\sа потом\s|\sпотом\s|\sзатем\s|\sпосле этого\s)\s*/)
    .map((s) => s.trim())
    .filter(Boolean);
  // «открой телеграм и открой почту», «открой телеграм открой почту» — режем перед глаголом.
  const out = [];
  for (const part of parts) {
    let cur = [];
    for (const w of part.split(' ')) {
      const v = canonVerb(w);
      const starts = ACTION_VERBS.has(v) || (COMMAND_WORDS.has(w) && cur[cur.length - 1] === 'и') || STRONG_WORDS.has(w);
      if (cur.length && starts && !['сделай', 'поставь', 'на'].includes(cur[cur.length - 1])) {
        if (cur[cur.length - 1] === 'и') cur.pop();
        if (cur.length) out.push(cur.join(' '));
        cur = [];
      }
      cur.push(w);
    }
    if (cur.length) out.push(cur.join(' '));
  }
  return out;
}

const ACTION_VERBS = new Set([...VERB_FORMS.map(([, v]) => v)]);
// Слова, с которых тоже начинается отдельная команда: «… и громкость 30», «… яркость 50».
const STRONG_WORDS = new Set(['громкость', 'яркость', 'громче', 'тише', 'ярче', 'темнее', 'пауза', 'скриншот']);
const COMMAND_WORDS = new Set([...STRONG_WORDS, 'таймер', 'погода', 'звук', 'музыку', 'следующий', 'новая', 'курс', 'который']);

/**
 * Разбор обучения: «когда я говорю рабочий режим открой телеграм и почту».
 * Возвращает { phrase, actions[] } или null.
 */
export function parseTeach(rest) {
  let phrase = '';
  let action = '';
  const sep = rest.match(/^(.+?)\s*(?::|—|\s-\s|\s(?:то|тогда|значит|это значит|это означает|означает|делай|выполняй|ты должен|ты делаешь|нужно|надо|это)\s)\s*(.+)$/);
  if (sep) {
    phrase = sep[1];
    action = sep[2];
  } else {
    const words = rest.split(' ');
    for (let i = 1; i < words.length; i++) {
      if (VERBS.has(canonVerb(words[i]))) {
        phrase = words.slice(0, i).join(' ');
        action = words.slice(i).join(' ');
        break;
      }
    }
  }
  phrase = phrase.replace(/^(фразу|слово|слова|команду)\s+/, '').trim();
  const actions = splitActions(action).map((a) => {
    const w = a.split(' ');
    w[0] = canonVerb(w[0]);
    return w.join(' ');
  });
  if (!phrase || !actions.length) return null;
  return { phrase, actions };
}
