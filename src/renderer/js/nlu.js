export const VERBS = new Set(VERB_FORMS.map(([, v]) => v).concat(['поставь', 'громче', 'тише', 'пауза']));

export function canonVerb(word) {
  for (const [re, v] of VERB_FORMS) if (re.test(word)) return v;
  return word;
}

/** Приводит фразу к виду, удобному для правил: без вступлений, с цифрами, с канонич. глаголом впереди. */
export function cleanCommand(text) {
  let t = normalize(text)
    .replace(/-ка(?=\s|$)/g, '')
    .replace(/(^|\s)(пожалуйста|плиз|пжл|пж|пожалуйсто)(?=\s|$)/g, ' ')
    .replace(/[,;!?]+/g, ' ')
    .replace(/:(?!\d)/g, ' ')
    .replace(/\s-\s/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  for (let i = 0; i < 5; i++) {
    const next = t.replace(LEAD, '');
    if (next === t) break;
    t = next;
  }
  t = t.replace(/\s+(срочно|быстро|скорее|побыстрее|сейчас же)$/, '').trim();
  t = wordsToNumbers(t);
  const words = t.split(' ').filter(Boolean);
  if (!words.length) return '';
  words[0] = canonVerb(words[0]);
  // «ютуб открой» → «открой ютуб»
  if (words.length > 1 && !VERBS.has(words[0])) {
    const last = canonVerb(words[words.length - 1]);
    if (['открой', 'запусти', 'включи', 'выключи', 'закрой', 'найди', 'покажи', 'сделай', 'поставь', 'сверни', 'разверни'].includes(last)) {
      words.pop();
      words.unshift(last);
    }
  }
  return words.join(' ');
}

